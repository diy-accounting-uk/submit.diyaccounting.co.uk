// Usage:
//   node scripts/ai-vendor-ranges.mjs refresh    fetch each vendor list, rewrite the JSON and the view
//   node scripts/ai-vendor-ranges.mjs generate   rewrite the view from the committed JSON
//   node scripts/ai-vendor-ranges.mjs check      exit 1 when the committed view differs from the JSON

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const RANGES_PATH = join(ROOT, "infra", "analytics", "ai-vendor-ranges.json");
export const VIEW_PATH = join(ROOT, "infra", "main", "resources", "analytics", "views", "v_ai_fetches_daily.sql");

const CIDR = /^(?:\d{1,3}(?:\.\d{1,3}){3}\/\d{1,2}|[0-9a-f:]+:[0-9a-f:]*\/\d{1,3})$/i;

export function parsePrefixesJson(text) {
  const parsed = JSON.parse(text);
  if (!Array.isArray(parsed.prefixes)) throw new Error("no prefixes array");
  return parsed.prefixes.map((p) => p.ipv4Prefix ?? p.ipv6Prefix).filter(Boolean);
}

// The page lists inbound and outbound addresses. The vendor's agents fetch from the outbound ones.
export function parseAnthropicOutboundMarkdown(text) {
  const start = text.indexOf("## Outbound IP addresses");
  if (start === -1) throw new Error("no Outbound IP addresses section");
  const rest = text.slice(start + 1);
  const end = rest.search(/\n### Phased out|\n## /);
  const section = end === -1 ? rest : rest.slice(0, end);
  return [...section.matchAll(/`([^`\s]+\/\d+)`/g)].map((m) => m[1]);
}

const PARSERS = {
  "prefixes-json": parsePrefixesJson,
  "anthropic-outbound-markdown": parseAnthropicOutboundMarkdown,
};

export function normaliseCidrs(cidrs) {
  const bad = cidrs.filter((c) => !CIDR.test(c));
  if (bad.length > 0) throw new Error(`not a CIDR: ${bad.join(", ")}`);
  return [...new Set(cidrs.map((c) => c.toLowerCase()))].sort();
}

export function loadRanges(path = RANGES_PATH) {
  return JSON.parse(readFileSync(path, "utf-8"));
}

export async function refreshRanges(ranges, fetchText) {
  const sources = [];
  for (const source of ranges.sources) {
    const parse = PARSERS[source.format];
    if (!parse) throw new Error(`unknown format ${source.format} for ${source.url}`);
    const cidrs = normaliseCidrs(parse(await fetchText(source.url)));
    if (cidrs.length === 0) throw new Error(`${source.url} returned no ranges`);
    sources.push({ ...source, cidrs });
  }
  return { sources };
}

export async function renderRangesJson(ranges) {
  const options = (await prettier.resolveConfig(RANGES_PATH)) ?? {};
  return prettier.format(JSON.stringify(ranges), { ...options, parser: "json" });
}

export function renderViewSql(ranges) {
  const rows = ranges.sources.flatMap((source) =>
    source.agents.flatMap((agent) => source.cidrs.map((cidr) => `    ('${agent}', '${cidr}')`)),
  );
  return `-- SPDX-License-Identifier: LicenseRef-PolyForm-Internal-Use-1.0.0
-- Copyright (C) 2006-2026 DIY Accounting Limited

-- GENERATED by scripts/ai-vendor-ranges.mjs from infra/analytics/ai-vendor-ranges.json. Edit
-- neither the VALUES list nor the SQL here: change the script and run it.
-- Requests each day to Submit's own distributions by the AI and search agent that the user
-- agent names, with a path and a verified flag. An agent's name is not proof of who fetched.
-- verified is true when the request's address is inside the ranges that the agent's vendor
-- publishes for that agent. Googlebot and bingbot publish no list read here, so their
-- verified is always false. Our own tests and Claude Code sessions are claude-code or other
-- and are false.
-- c_ip is personal data. It is read only inside the range test, whose output is a boolean,
-- and the view never selects it or a hash of it.
CREATE OR REPLACE VIEW v_ai_fetches_daily AS
WITH vendor_ranges (agent, cidr) AS (
  VALUES
${rows.join(",\n")}
),
requests AS (
  SELECT date,
         cs_uri_stem AS path,
         c_ip,
         lower(coalesce(try(url_decode(cs_user_agent)), cs_user_agent)) AS ua
  FROM   cloudfront_requests
),
named AS (
  SELECT date, path, c_ip,
         CASE
           WHEN ua LIKE '%claude-code%' THEN 'claude-code'
           WHEN ua LIKE '%oai-searchbot%' THEN 'OAI-SearchBot'
           WHEN ua LIKE '%chatgpt-user%' THEN 'ChatGPT-User'
           WHEN ua LIKE '%gptbot%' THEN 'GPTBot'
           WHEN ua LIKE '%claude-searchbot%' THEN 'Claude-SearchBot'
           WHEN ua LIKE '%claude-user%' THEN 'Claude-User'
           WHEN ua LIKE '%claudebot%' THEN 'ClaudeBot'
           WHEN ua LIKE '%perplexitybot%' THEN 'PerplexityBot'
           WHEN ua LIKE '%perplexity-user%' THEN 'Perplexity-User'
           WHEN ua LIKE '%bingbot%' THEN 'bingbot'
           WHEN ua LIKE '%googlebot%' THEN 'Googlebot'
           ELSE 'other'
         END AS agent
  FROM   requests
),
checked AS (
  SELECT n.date, n.agent, n.path,
         EXISTS (
           SELECT 1
           FROM   vendor_ranges v
           WHERE  v.agent = n.agent
             AND  contains(v.cidr, try_cast(n.c_ip AS ipaddress))
         ) AS verified
  FROM   named n
)
SELECT CAST(date_parse(date, '%Y-%m-%d') AS date) AS day,
       agent,
       path,
       verified,
       count(*) AS requests
FROM   checked
GROUP  BY 1, 2, 3, 4
`;
}

export function viewIsStale(ranges, viewText) {
  return renderViewSql(ranges) !== viewText;
}

async function fetchText(url) {
  const response = await fetch(url, { headers: { "user-agent": "diyaccounting-ai-vendor-ranges" } });
  if (!response.ok) throw new Error(`${url} returned ${response.status}`);
  return response.text();
}

async function main(mode) {
  if (mode === "refresh") {
    const ranges = await refreshRanges(loadRanges(), fetchText);
    writeFileSync(RANGES_PATH, await renderRangesJson(ranges));
    writeFileSync(VIEW_PATH, renderViewSql(ranges));
    console.log(`ranges: ${ranges.sources.map((s) => `${s.agents.join("+")} ${s.cidrs.length}`).join(", ")}`);
  } else if (mode === "generate") {
    writeFileSync(VIEW_PATH, renderViewSql(loadRanges()));
  } else if (mode === "check") {
    if (viewIsStale(loadRanges(), readFileSync(VIEW_PATH, "utf-8"))) {
      console.error("v_ai_fetches_daily.sql is stale: run `node scripts/ai-vendor-ranges.mjs generate`");
      process.exit(1);
    }
  } else {
    console.error("usage: ai-vendor-ranges.mjs refresh|generate|check");
    process.exit(2);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main(process.argv[2]);

// scripts/build-developer-site.mjs
//
// Writes web/developer/mcp-api.html, the MCP API reference of the developer site: the server
// endpoint, every tool the submission MCP server registers, and each tool's input schema. The
// reference is read from the running server over an in-memory MCP client, so it cannot drift from
// mcp/lib/server.js; web/unit-tests/developer-site.test.js fails when the committed file is stale.
//
// Usage: node scripts/build-developer-site.mjs

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";

import { createSession } from "../mcp/lib/book-tools.js";
import { hostedToolNames } from "../mcp/lib/hosted-tools.js";
import { createServer, SERVER_INFO } from "../mcp/lib/server.js";

export const HOSTED_ENDPOINT = "https://submit.diyaccounting.co.uk/mcp";
export const MCP_API_PAGE = resolve(dirname(fileURLToPath(import.meta.url)), "..", "web", "developer", "mcp-api.html");

function escapeHtml(text) {
  return String(text ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function typeOf(schema) {
  if (!schema) return "";
  if (Array.isArray(schema.enum)) return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  if (schema.type === "array") return `${typeOf(schema.items) || "any"}[]`;
  if (Array.isArray(schema.type)) return schema.type.join(" | ");
  return schema.type ?? (schema.anyOf ? schema.anyOf.map(typeOf).join(" | ") : "");
}

export async function listServerTools() {
  const server = createServer(createSession());
  const client = new Client({ name: "diya-developer-site-build", version: "1.0.0" });
  const [clientSide, serverSide] = InMemoryTransport.createLinkedPair();
  await server.connect(serverSide);
  await client.connect(clientSide);
  try {
    const { tools } = await client.listTools();
    return tools.slice().sort((a, b) => a.name.localeCompare(b.name));
  } finally {
    await client.close();
    await server.close();
  }
}

function renderParameters(inputSchema) {
  const properties = Object.entries(inputSchema?.properties ?? {});
  if (properties.length === 0) return "<p>No parameters.</p>";
  const required = new Set(inputSchema.required ?? []);
  const rows = properties
    .map(
      ([name, schema]) =>
        `<tr><td><code>${escapeHtml(name)}</code></td><td>${escapeHtml(typeOf(schema))}</td><td>${required.has(name) ? "yes" : "no"}</td><td>${escapeHtml(schema.description ?? "")}</td></tr>`,
    )
    .join("\n            ");
  return `<table>
          <thead><tr><th>Parameter</th><th>Type</th><th>Required</th><th>Meaning</th></tr></thead>
          <tbody>
            ${rows}
          </tbody>
        </table>`;
}

export async function renderMcpApiPage() {
  const tools = await listServerTools();
  const prodHosted = new Set(hostedToolNames("prod"));
  const sections = tools
    .map(
      (tool) => `      <details class="tool" id="tool-${escapeHtml(tool.name)}">
        <summary><code>${escapeHtml(tool.name)}</code>${prodHosted.has(tool.name) ? ' <span class="tag">hosted, production</span>' : ""}</summary>
        <p>${escapeHtml(tool.description ?? "")}</p>
        ${renderParameters(tool.inputSchema)}
        <details>
          <summary>Input schema (JSON Schema)</summary>
          <pre><code>${escapeHtml(JSON.stringify(tool.inputSchema, null, 2))}</code></pre>
        </details>
      </details>`,
    )
    .join("\n");

  return `<!doctype html>
<!-- SPDX-License-Identifier: LicenseRef-PolyForm-Internal-Use-1.0.0 -->
<!-- Copyright (C) 2006-2026 DIY Accounting Limited -->
<!-- Generated by scripts/build-developer-site.mjs from mcp/lib/server.js. Do not edit by hand. -->
<html lang="en-GB">
  <head>
    <meta charset="UTF-8" />
    <title>MCP API - DIY Accounting Developers</title>
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta name="description" content="The DIY Accounting Submit MCP server: endpoint, tools and input schemas." />
    <link rel="icon" href="favicon.svg" type="image/svg+xml" />
    <link rel="stylesheet" href="developer.css" />
  </head>
  <body>
    <a href="#mainContent" class="skip-link">Skip to main content</a>
    <header>
      <h1>MCP API</h1>
      <p class="nav"><a href="./">Developers</a></p>
    </header>
    <main id="mainContent">
      <section class="panel">
        <h2>Server</h2>
        <p>Server name <code>${escapeHtml(SERVER_INFO.name)}</code>, version <code>${escapeHtml(SERVER_INFO.version)}</code>.</p>
        <p>The hosted endpoint speaks streamable HTTP and signs in with OAuth:</p>
        <pre><code>${escapeHtml(HOSTED_ENDPOINT)}</code></pre>
        <p>
          The same tools run locally over stdio from the npm package
          <a href="https://www.npmjs.com/package/@diy-accounting-uk/diya-submit">@diy-accounting-uk/diya-submit</a>
          or the image <code>ghcr.io/diy-accounting-uk/diya-submit-mcp</code>. The hosted production endpoint registers the tools tagged
          below; other environments register more.
        </p>
      </section>
      <section class="panel">
        <h2>Tools (${tools.length})</h2>
${sections}
      </section>
    </main>
  </body>
</html>
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(MCP_API_PAGE, await renderMcpApiPage());
  console.log(`Wrote ${MCP_API_PAGE}`);
}

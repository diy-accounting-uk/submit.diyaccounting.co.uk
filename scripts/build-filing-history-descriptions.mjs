// Usage:
//   node scripts/build-filing-history-descriptions.mjs refresh   fetch Companies House's filing history descriptions at the
//                                                               pinned commit and rewrite the vendored module
//   node scripts/build-filing-history-descriptions.mjs check     exit 1 when the vendored module differs from that source
//
// The company lookup's drill-down shows each filing in Companies House's own words. Those words are
// the description enumeration of github.com/companieshouse/api-enumerations, file
// filing_history_descriptions.yml. Only its description map is vendored, with the bold markers
// dropped, because the page shows each description as plain text.

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const MODULE_PATH = join(ROOT, "web", "public", "lib", "company", "filing-history-descriptions.js");
export const SOURCE_REPOSITORY = "https://github.com/companieshouse/api-enumerations";
export const SOURCE_COMMIT = "05067abc50da2c9277bb5d3504187f55e5ec9e24";
export const SOURCE_URL = `https://raw.githubusercontent.com/companieshouse/api-enumerations/${SOURCE_COMMIT}/filing_history_descriptions.yml`;

const ENTRY = /^\s+'([^']+)'\s*:\s*"(.*)"\s*$/;

/** The description map of filing_history_descriptions.yml: each description key and its words, bold markers dropped. */
export function parseDescriptions(yaml) {
  const lines = yaml.split("\n");
  const start = lines.findIndex((line) => line.trim() === "description:");
  if (start === -1) throw new Error("no description map");
  const descriptions = {};
  for (const line of lines.slice(start + 1)) {
    if (/^\S/.test(line)) break;
    const match = ENTRY.exec(line);
    if (match) descriptions[match[1]] = match[2].replace(/\*\*/g, "").replace(/\\"/g, '"');
  }
  if (Object.keys(descriptions).length === 0) throw new Error("the description map is empty");
  return descriptions;
}

export async function moduleText(descriptions) {
  const text = `// SPDX-License-Identifier: LicenseRef-PolyForm-Internal-Use-1.0.0
// Copyright (C) 2006-2026 DIY Accounting Limited

// Generated by scripts/build-filing-history-descriptions.mjs; run it with "refresh" to change this file.
// Source: ${SOURCE_REPOSITORY}, filing_history_descriptions.yml, commit ${SOURCE_COMMIT}.
// Companies House publishes that repository with no licence file; its words are the register's own
// descriptions of each filing, as the Companies House service shows them.

window.filingHistoryDescriptions = ${JSON.stringify(descriptions)};
`;
  return prettier.format(text, { ...(await prettier.resolveConfig(MODULE_PATH)), filepath: MODULE_PATH });
}

async function fetchSource() {
  const response = await fetch(SOURCE_URL);
  if (!response.ok) throw new Error(`${SOURCE_URL} answered ${response.status}`);
  return response.text();
}

async function main(command) {
  const expected = await moduleText(parseDescriptions(await fetchSource()));
  if (command === "refresh") {
    writeFileSync(MODULE_PATH, expected);
    console.log(`Wrote ${MODULE_PATH}`);
  } else if (command === "check") {
    if (readFileSync(MODULE_PATH, "utf8") !== expected) {
      console.error(`${MODULE_PATH} differs from ${SOURCE_URL}; run refresh`);
      process.exit(1);
    }
    console.log(`${MODULE_PATH} matches ${SOURCE_URL}`);
  } else {
    console.error("Usage: node scripts/build-filing-history-descriptions.mjs refresh|check");
    process.exit(2);
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main(process.argv[2]);
